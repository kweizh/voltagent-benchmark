import { VoltAgent, Agent, createWorkflowChain } from "@voltagent/core";
import { honoServer } from "@voltagent/server-hono";
import { openai } from "@ai-sdk/openai";
import { z } from "zod";

// Define the schema for the structured JSON payload
const PayloadSchema = z.object({
  extractedData: z.record(z.string(), z.string()).describe("The structured data extracted from the input text"),
  analysis: z.string().optional().describe("The analysis/summary generated by the processor"),
});

// Define the receiver agent
const receiver = new Agent({
  id: "receiver",
  name: "receiver",
  instructions: "You are a data extraction agent. Your task is to extract relevant information from the incoming text and format it as a structured JSON object. Focus on identifying key entities, dates, and values.",
  model: openai("gpt-4o-mini"),
});

// Define the processor agent
const processor = new Agent({
  id: "processor",
  name: "processor",
  instructions: "You are an analysis agent. Your task is to take the structured JSON data provided and generate a concise summary and analysis of the information. Focus on trends or important insights.",
  model: openai("gpt-4o-mini"),
});

// Create the workflow chain
const workflow = createWorkflowChain({
  id: "a2a-workflow",
  input: z.object({ text: z.string() }),
  output: PayloadSchema,
})
  .andAgent(
    ({ data }) => `Extract structured data from the following text: ${data.text}`,
    receiver,
    { schema: z.object({ extractedData: z.record(z.string(), z.string()) }) }
  )
  .andAgent(
    ({ data }) => `Analyze the following extracted data and provide a summary: ${JSON.stringify(data.extractedData)}`,
    processor,
    { schema: z.object({ analysis: z.string() }) },
    (output, { data }) => ({
      extractedData: data.extractedData,
      analysis: output.analysis,
    })
  );

// Initialize and start the VoltAgent server
const server = new VoltAgent({
  agents: { receiver, processor },
  workflows: { workflow },
  server: honoServer({
    port: 3000,
    configureApp: (app) => {
      // Expose the endpoint to trigger the workflow
      app.post("/api/process", async (c) => {
        try {
          const body = await c.req.json();
          const { text } = body;

          if (!text) {
            return c.json({ error: "Missing 'text' in request body" }, 400);
          }

          console.log(`Triggering workflow with input: ${text}`);
          
          // Run the workflow
          const result = await workflow.run({ text });
          
          return c.json({
            success: true,
            result
          });
        } catch (error: any) {
          console.error("Workflow execution failed:", error);
          return c.json({
            success: false,
            error: error.message
          }, 500);
        }
      });
    }
  }),
});

console.log("VoltAgent A2A Protocol Server is running on port 3000");
